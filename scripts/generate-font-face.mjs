import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontRoot = join(projectRoot, 'public', 'fonts');
const formats = [
  ['woff2', 'font/woff2', 'woff2'],
  ['woff', 'font/woff', 'woff'],
  ['ttf', 'font/ttf', 'truetype'],
];

const sources = formats.map(([extension, mime, format]) => {
  const font = readFileSync(join(fontRoot, `DaysOne-Regular.${extension}`));
  return `url("data:${mime};base64,${font.toString('base64')}") format("${format}")`;
});

const css = `/* Generated by scripts/generate-font-face.mjs from the user-provided OFL font. */
@font-face {
  font-family: "Days One";
  src: ${sources.join(',\n       ')};
  font-style: normal;
  font-weight: 400;
  font-display: swap;
}
`;

writeFileSync(join(projectRoot, 'public', 'font-face.css'), css);
